// MapLibre 6 loads its tile worker as a separate ES module, so the two files
// below have to be served from /public and handed to setWorkerUrl.
//
// They used to be checked in, which let them fall a major version behind the
// installed package: a v6 worker ran against a v5 bundle and no tile was ever
// requested, blanking every map. Copying them from node_modules on each build
// keeps the pair pinned to whatever version is actually installed.

import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FILES = ["maplibre-gl-worker.mjs", "maplibre-gl-shared.mjs"];

const require = createRequire(import.meta.url);
const pkgPath = require.resolve("maplibre-gl/package.json");
const dist = join(dirname(pkgPath), "dist");
const publicDir = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const version = require(pkgPath).version;
const versionDir = join(publicDir, "maplibre", version);
const generatedDir = join(rootDir, "lib", "generated");

await mkdir(versionDir, { recursive: true });
for (const file of FILES) {
  const destination = join(versionDir, file);
  let current;
  try { current = await readFile(destination); } catch { current = undefined; }
  const source = await readFile(join(dist, file));
  if (!current?.equals(source)) await copyFile(join(dist, file), destination);
}

await mkdir(generatedDir, { recursive: true });
const generatedPath = join(generatedDir, "maplibre-worker.ts");
const generated = `// Generated by scripts/copy-maplibre-worker.mjs.\nexport const MAPLIBRE_WORKER_URL = "/maplibre/${version}/maplibre-gl-worker.mjs";\n`;
let currentGenerated;
try { currentGenerated = await readFile(generatedPath, "utf8"); } catch { currentGenerated = undefined; }
if (currentGenerated !== generated) await writeFile(generatedPath, generated, "utf8");

console.log(`Prepared immutable MapLibre ${version} worker modules.`);
